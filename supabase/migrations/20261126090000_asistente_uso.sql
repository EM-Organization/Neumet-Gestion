-- =============================================================================
-- NEUMET · Asistente de reportes con IA: cuota diaria y registro de uso (docs/24 §4, §7, §9)
-- =============================================================================
-- Requiere 20261106000000_init_schema.sql (clientes, perfiles, is_admin), 20261107020000_seccionales.sql
-- (sucursales, perfiles.sucursal_id), 20261116500000_privilegios_precios.sql (precios_visibles) y
-- 20261126050000_calidad_moneda.sql (clientes.moneda_default).
-- Sin begin/commit: la herramienta que aplica la migración ya la envuelve. Idempotente (el CI la aplica dos veces).
--
-- Qué agrega:
--   1. Tabla asistente_uso: una fila por pregunta (usuario, cliente, día, tools, modelo, tokens, costo, resultado).
--      Sin texto de la pregunta ni de la respuesta (docs/24 §9). Un usuario ve sus filas; el admin, todas.
--   2. asistente_reservar(p_cliente_id): autoriza la pregunta según el perfil, aplica la cuota de 30 por usuario
--      y día y registra la fila «en_curso». Devuelve el alcance (cliente, sucursal, costos visibles) que la
--      Edge Function usa para acotar las tools.
--   3. asistente_cerrar(...): cierra la fila propia «en_curso» con su resultado y sus cifras.
--
-- Por qué RPC y no service_role: la función asistente-reportes escribe el registro con el JWT del usuario, igual que
-- sus tools (docs/24 §4.1). La cuota no se puede saltar porque solo asistente_reservar inserta, y asistente_cerrar
-- no puede borrar ni pasar una fila a «cuota». Riesgo aceptado: un usuario podría alterar las cifras de sus propias
-- filas; sirven para monitoreo y el gasto lo topa OpenRouter.
--
-- Día de la cuota: el día calendario de Montevideo (lo fija asistente_reservar al insertar, no un default).
-- Una petición que nunca cierra queda «en_curso» y cuenta como usada: gastó cupo. No hay limpieza.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. Tabla
-- -----------------------------------------------------------------------------
create table if not exists public.asistente_uso (
  id              bigint generated by default as identity primary key,
  user_id         uuid not null references auth.users (id) on delete cascade,
  cliente_id      bigint not null references public.clientes (id) on delete cascade,
  dia             date not null,
  created_at      timestamptz not null default now(),
  resultado       text not null default 'en_curso'
                  check (resultado in ('en_curso', 'ok', 'error', 'cuota')),
  modelo          text check (length(modelo) <= 100),
  tools           text[] check (cardinality(tools) <= 20),
  tokens_entrada  integer check (tokens_entrada >= 0),
  tokens_salida   integer check (tokens_salida >= 0),
  duracion_ms     integer check (duracion_ms >= 0),
  costo           numeric(12,6) check (costo >= 0),
  prompt_version  text check (length(prompt_version) <= 20),
  aviso           text check (length(aviso) <= 60),
  cerrada_at      timestamptz
);

create index if not exists asistente_uso_user_dia_idx on public.asistente_uso (user_id, dia);
-- A lo sumo una fila de «cuota» por usuario y día: la segunda pregunta rechazada no agrega filas.
create unique index if not exists asistente_uso_cuota_uk on public.asistente_uso (user_id, dia)
  where resultado = 'cuota';

alter table public.asistente_uso enable row level security;
-- Los privilegios por defecto de public dan todo a anon y authenticated: se revocan y se da solo SELECT.
-- Sin política ni grant de insert/update/delete: solo las RPC SECURITY DEFINER escriben.
revoke all on table public.asistente_uso from public, anon, authenticated;
revoke all on sequence public.asistente_uso_id_seq from public, anon, authenticated;
grant select on table public.asistente_uso to authenticated;

drop policy if exists asistente_uso_select on public.asistente_uso;
create policy asistente_uso_select on public.asistente_uso for select to authenticated
  using (user_id = (select auth.uid()) or (select public.is_admin()));

-- -----------------------------------------------------------------------------
-- 2. asistente_reservar: autoriza, cuenta la cuota y registra la pregunta
-- -----------------------------------------------------------------------------
-- Rechazo uniforme: sin perfil, perfil api o empresa dada de baja → 42501 (no revela si el usuario existe).
-- El admin debe elegir cliente (22023 «cliente_requerido»); un perfil de cliente usa su propio cliente y p_cliente_id se
-- ignora (el modelo ni el panel pueden cambiar de empresa).
-- El bloqueo por usuario hace que dos preguntas simultáneas no lean ambas 29 y pasen las dos: la segunda espera a que
-- la primera confirme y cuenta 30.
create or replace function public.asistente_reservar(p_cliente_id bigint default null)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_uid           uuid := auth.uid();
  v_rol_perfil    text;
  v_perfil_cli    bigint;
  v_perfil_suc    bigint;
  v_cliente_id    bigint;
  v_cliente_nom   text;
  v_moneda        text;
  v_deleted       timestamptz;
  v_rol           text;
  v_suc_id        bigint;
  v_suc_nom       text;
  v_dia           date := (now() at time zone 'America/Montevideo')::date;
  v_usadas        integer;
  v_id            bigint;
  c_limite constant integer := 30;
begin
  if v_uid is null then
    raise exception 'sin sesión' using errcode = '42501';
  end if;

  select p.rol, p.cliente_id, p.sucursal_id
    into v_rol_perfil, v_perfil_cli, v_perfil_suc
    from public.perfiles p where p.user_id = v_uid;
  if not found or v_rol_perfil = 'api' then
    raise exception 'permiso denegado' using errcode = '42501';
  end if;

  if v_rol_perfil = 'admin' then
    if p_cliente_id is null then
      raise exception 'cliente_requerido' using errcode = '22023';
    end if;
    select c.id, c.nombre, c.moneda_default, c.deleted_at
      into v_cliente_id, v_cliente_nom, v_moneda, v_deleted
      from public.clientes c where c.id = p_cliente_id;
    if not found or v_deleted is not null then
      raise exception 'cliente_requerido' using errcode = '22023';
    end if;
    v_rol := 'admin';
  else
    -- rol 'cliente': el cliente y la sucursal salen del perfil, nunca de p_cliente_id
    select c.id, c.nombre, c.moneda_default, c.deleted_at
      into v_cliente_id, v_cliente_nom, v_moneda, v_deleted
      from public.clientes c where c.id = v_perfil_cli;
    if not found or v_deleted is not null then
      raise exception 'permiso denegado' using errcode = '42501';
    end if;
    if v_perfil_suc is null then
      v_rol := 'global';
    else
      select s.id, s.nombre into v_suc_id, v_suc_nom
        from public.sucursales s
        where s.id = v_perfil_suc and s.cliente_id = v_cliente_id;
      if not found then
        raise exception 'permiso denegado' using errcode = '42501';
      end if;
      v_rol := 'sucursal';
    end if;
  end if;

  -- Serializa las preguntas de un mismo usuario hasta el fin de la transacción (usuarios distintos no se bloquean).
  perform pg_advisory_xact_lock(hashtextextended('asistente_uso:' || v_uid::text, 0));

  select count(*) into v_usadas
    from public.asistente_uso u
    where u.user_id = v_uid and u.dia = v_dia and u.resultado <> 'cuota';

  if v_usadas >= c_limite then
    insert into public.asistente_uso (user_id, cliente_id, dia, resultado)
      values (v_uid, v_cliente_id, v_dia, 'cuota')
      on conflict (user_id, dia) where resultado = 'cuota' do nothing;
    return jsonb_build_object('permitido', false, 'usadas', v_usadas, 'limite', c_limite);
  end if;

  insert into public.asistente_uso (user_id, cliente_id, dia, resultado)
    values (v_uid, v_cliente_id, v_dia, 'en_curso')
    returning id into v_id;

  return jsonb_build_object(
    'permitido', true,
    'id', v_id,
    'usadas', v_usadas + 1,
    'limite', c_limite,
    'rol', v_rol,
    'cliente_id', v_cliente_id,
    'cliente_nombre', v_cliente_nom,
    'sucursal_id', v_suc_id,
    'sucursal_nombre', v_suc_nom,
    'costos_visibles', public.precios_visibles(),
    'moneda_default', v_moneda
  );
end
$$;
revoke all on function public.asistente_reservar(bigint) from public, anon;
grant execute on function public.asistente_reservar(bigint) to authenticated;

-- -----------------------------------------------------------------------------
-- 3. asistente_cerrar: cierra la fila propia «en_curso»
-- -----------------------------------------------------------------------------
-- Valida antes del update con mensajes claros (22023); el check de la tabla queda como respaldo. Devuelve false si la
-- fila no es del usuario, no existe o ya estaba cerrada: un cierre repetido no cambia nada.
create or replace function public.asistente_cerrar(
  p_id              bigint,
  p_resultado       text,
  p_modelo          text default null,
  p_tools           text[] default null,
  p_tokens_entrada  integer default null,
  p_tokens_salida   integer default null,
  p_costo           numeric default null,
  p_duracion_ms     integer default null,
  p_prompt_version  text default null,
  p_aviso           text default null
)
returns boolean
language plpgsql
volatile
security definer
set search_path = ''
as $$
begin
  if p_resultado is null or p_resultado not in ('ok', 'error') then
    raise exception 'resultado inválido' using errcode = '22023';
  end if;
  if length(p_modelo) > 100 then
    raise exception 'modelo demasiado largo' using errcode = '22023';
  end if;
  if coalesce(cardinality(p_tools), 0) > 20 then
    raise exception 'demasiadas tools' using errcode = '22023';
  end if;
  if p_tokens_entrada < 0 or p_tokens_salida < 0 or p_duracion_ms < 0 or p_costo < 0 then
    raise exception 'valor negativo' using errcode = '22023';
  end if;
  if length(p_prompt_version) > 20 then
    raise exception 'prompt_version demasiado largo' using errcode = '22023';
  end if;
  if length(p_aviso) > 60 then
    raise exception 'aviso demasiado largo' using errcode = '22023';
  end if;

  update public.asistente_uso u
    set resultado      = p_resultado,
        modelo         = coalesce(p_modelo, u.modelo),
        tools          = coalesce(p_tools, u.tools),
        tokens_entrada = coalesce(p_tokens_entrada, u.tokens_entrada),
        tokens_salida  = coalesce(p_tokens_salida, u.tokens_salida),
        costo          = coalesce(p_costo, u.costo),
        duracion_ms    = coalesce(p_duracion_ms, u.duracion_ms),
        prompt_version = coalesce(p_prompt_version, u.prompt_version),
        aviso          = coalesce(p_aviso, u.aviso),
        cerrada_at     = now()
    where u.id = p_id and u.user_id = auth.uid() and u.resultado = 'en_curso';
  return found;
end
$$;
revoke all on function public.asistente_cerrar(bigint, text, text, text[], integer, integer, numeric, integer, text, text) from public, anon;
grant execute on function public.asistente_cerrar(bigint, text, text, text[], integer, integer, numeric, integer, text, text) to authenticated;
