-- 4. Helpers de validación (solo los llaman funciones SECURITY DEFINER; no son API)
-- -----------------------------------------------------------------------------
-- Odómetro obligatorio por cliente (RN-12). El mensaje contiene «odometro» a propósito: el handler de la API lo reconoce.
create or replace function public.odometro_obligatorio_validar(p_cliente_id bigint, p_odometro_km integer)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if p_odometro_km is null and exists (select 1 from public.clientes c
                                        where c.id = p_cliente_id and c.odometro_obligatorio) then
    raise exception 'odometro obligatorio: indicar la lectura del odómetro del vehículo' using errcode = '22023';
  end if;
end
$$;
revoke all on function public.odometro_obligatorio_validar(bigint, integer) from public, anon, authenticated;

