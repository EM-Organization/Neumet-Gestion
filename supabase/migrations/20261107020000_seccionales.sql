-- =============================================================================
-- NEUMET · Seccionales (sucursales) por cliente: perfil global vs. perfil de seccional
-- =============================================================================
-- Requiere 20261106000000_init_schema.sql y 20261106020000_producto_vistas.sql
-- (is_admin(), current_cliente_id(), audit_row(), eventos_neumatico, vistas v_*).
-- Sin begin/commit: la herramienta que aplica la migración ya la envuelve.
-- Idempotente (se puede reaplicar). Mismas reglas de seguridad que las anteriores:
--   defecto = denegar; RLS en la tabla nueva; anon sin nada; SECURITY DEFINER con
--   search_path=''; vistas con security_invoker (heredan la RLS de las tablas).
--
-- MODELO
--   * Un cliente (empresa) puede tener N seccionales (p. ej. "Montevideo", "Salto").
--   * perfiles.sucursal_id NULL  => perfil GLOBAL del cliente: ve todas sus filas.
--     perfiles.sucursal_id = X   => perfil de SECCIONAL: solo ve las filas cuyo
--     vehículo (o dispositivo) pertenece a X. Hay un único rol 'cliente' (sin rol nuevo).
--   * vehiculos.sucursal_id / dispositivos.sucursal_id NULL => "sin seccional":
--     solo lo ve un perfil global.
--   * Un perfil de seccional NO ve: stock del cliente, otras seccionales, mediciones
--     sin vehículo, eventos sin vehículo. Tampoco puede escribir nada (no hay
--     políticas de escritura para el rol cliente), así que no edita umbrales.
--
-- ON DELETE: RESTRICT en TODAS las FK hacia sucursales. Motivo de seguridad: con
--   SET NULL, borrar una seccional convertiría en GLOBAL (ve todo el cliente) a
--   sus perfiles, y dejaría vehículos "sin seccional" sin aviso. Para borrar una
--   seccional hay que reasignar o eliminar antes sus vehículos, dispositivos y usuarios.
-- Coherencia de cliente: FK compuestas (sucursal_id, cliente_id) -> sucursales
--   (id, cliente_id). Con MATCH SIMPLE no se comprueba si sucursal_id es NULL.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. Tabla sucursales
-- -----------------------------------------------------------------------------
create table if not exists public.sucursales (
  id         bigint generated by default as identity primary key,
  cliente_id bigint not null references public.clientes (id) on delete restrict,
  nombre     text not null check (length(btrim(nombre)) > 0 and length(nombre) <= 100),
  created_at timestamptz not null default now(),
  -- Objetivo de las FK compuestas (sucursal y cliente coherentes).
  constraint sucursales_id_cliente_uk unique (id, cliente_id)
);
-- Nombre único por cliente, sin distinguir mayúsculas ni espacios de los bordes.
create unique index if not exists sucursales_cliente_nombre_uk
  on public.sucursales (cliente_id, lower(btrim(nombre)));

revoke all on table public.sucursales from public, anon, authenticated;
alter table public.sucursales enable row level security;
grant select, insert, update, delete on public.sucursales to authenticated;

drop trigger if exists trg_audit_sucursales on public.sucursales;
create trigger trg_audit_sucursales after insert or update or delete on public.sucursales
  for each row execute function public.audit_row();

-- -----------------------------------------------------------------------------
-- 2. Columnas de asignación (nullable) con FK compuesta
-- -----------------------------------------------------------------------------
alter table public.vehiculos    add column if not exists sucursal_id bigint;
alter table public.dispositivos add column if not exists sucursal_id bigint;
alter table public.perfiles     add column if not exists sucursal_id bigint;
-- Email informativo del usuario (lo escribe la función crear-usuario-seccional);
-- NO se usa para autenticar ni autorizar.
alter table public.perfiles     add column if not exists email text;

alter table public.vehiculos drop constraint if exists vehiculos_sucursal_fk;
alter table public.vehiculos add constraint vehiculos_sucursal_fk
  foreign key (sucursal_id, cliente_id) references public.sucursales (id, cliente_id)
  on delete restrict on update restrict;

alter table public.dispositivos drop constraint if exists dispositivos_sucursal_fk;
alter table public.dispositivos add constraint dispositivos_sucursal_fk
  foreign key (sucursal_id, cliente_id) references public.sucursales (id, cliente_id)
  on delete restrict on update restrict;

alter table public.perfiles drop constraint if exists perfiles_sucursal_fk;
alter table public.perfiles add constraint perfiles_sucursal_fk
  foreign key (sucursal_id, cliente_id) references public.sucursales (id, cliente_id)
  on delete restrict on update restrict;

-- Solo el rol 'cliente' puede estar restringido a una seccional (admin y api no).
alter table public.perfiles drop constraint if exists perfiles_sucursal_rol_ck;
alter table public.perfiles add constraint perfiles_sucursal_rol_ck
  check (sucursal_id is null or rol = 'cliente');

create index if not exists vehiculos_sucursal_idx    on public.vehiculos (sucursal_id)    where sucursal_id is not null;
create index if not exists dispositivos_sucursal_idx on public.dispositivos (sucursal_id) where sucursal_id is not null;
create index if not exists perfiles_sucursal_idx     on public.perfiles (sucursal_id)     where sucursal_id is not null;

-- -----------------------------------------------------------------------------
-- 3. Helper: seccional del usuario actual (NULL = global o sin perfil de cliente)
-- -----------------------------------------------------------------------------
-- Siempre se usa junto con current_cliente_id(): un usuario sin perfil de cliente
-- tiene cliente_id NULL y ninguna política le da acceso.
create or replace function public.current_sucursal_id()
returns bigint
language sql
stable
security definer
set search_path = ''
as $$
  select p.sucursal_id from public.perfiles p
  where p.user_id = (select auth.uid()) and p.rol = 'cliente'
$$;
revoke all on function public.current_sucursal_id() from public, anon;
grant execute on function public.current_sucursal_id() to authenticated;

-- -----------------------------------------------------------------------------
-- 4. Políticas (el rol admin no cambia)
-- -----------------------------------------------------------------------------
-- 4.1 sucursales: admin todo; cliente ve las de su cliente (la suya si es de seccional)
drop policy if exists sucursales_admin_all on public.sucursales;
create policy sucursales_admin_all on public.sucursales for all to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));
drop policy if exists sucursales_cliente_select on public.sucursales;
create policy sucursales_cliente_select on public.sucursales for select to authenticated
  using (cliente_id = (select public.current_cliente_id())
         and ((select public.current_sucursal_id()) is null or id = (select public.current_sucursal_id())));

-- 4.2 vehiculos
drop policy if exists vehiculos_cliente_select on public.vehiculos;
create policy vehiculos_cliente_select on public.vehiculos for select to authenticated
  using (cliente_id = (select public.current_cliente_id())
         and ((select public.current_sucursal_id()) is null or sucursal_id = (select public.current_sucursal_id())));

-- 4.3 dispositivos
drop policy if exists dispositivos_cliente_select on public.dispositivos;
create policy dispositivos_cliente_select on public.dispositivos for select to authenticated
  using (cliente_id = (select public.current_cliente_id())
         and ((select public.current_sucursal_id()) is null or sucursal_id = (select public.current_sucursal_id())));

-- 4.4 stock_neumaticos: inventario del cliente (con precios), solo perfil global
drop policy if exists stock_cliente_select on public.stock_neumaticos;
create policy stock_cliente_select on public.stock_neumaticos for select to authenticated
  using (cliente_id = (select public.current_cliente_id())
         and (select public.current_sucursal_id()) is null);

-- 4.5 neumaticos (a través del vehículo)
drop policy if exists neumaticos_cliente_select on public.neumaticos;
create policy neumaticos_cliente_select on public.neumaticos for select to authenticated
  using (exists (
    select 1 from public.vehiculos v
    where v.id = neumaticos.vehiculo_id
      and v.cliente_id = (select public.current_cliente_id())
      and ((select public.current_sucursal_id()) is null or v.sucursal_id = (select public.current_sucursal_id()))
  ));

-- 4.6 mediciones: de seccional solo las de vehículos de su seccional
drop policy if exists mediciones_cliente_select on public.mediciones;
create policy mediciones_cliente_select on public.mediciones for select to authenticated
  using (cliente_id = (select public.current_cliente_id())
         and ((select public.current_sucursal_id()) is null
              or exists (select 1 from public.vehiculos v
                         where v.id = mediciones.vehiculo_id
                           and v.cliente_id = mediciones.cliente_id
                           and v.sucursal_id = (select public.current_sucursal_id()))));

-- 4.7 eventos_neumatico
drop policy if exists eventos_cliente_select on public.eventos_neumatico;
create policy eventos_cliente_select on public.eventos_neumatico for select to authenticated
  using (cliente_id = (select public.current_cliente_id())
         and ((select public.current_sucursal_id()) is null
              or exists (select 1 from public.vehiculos v
                         where v.id = eventos_neumatico.vehiculo_id
                           and v.cliente_id = eventos_neumatico.cliente_id
                           and v.sucursal_id = (select public.current_sucursal_id()))));

