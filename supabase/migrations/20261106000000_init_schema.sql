-- 6.3 Sincronizar perfiles al crear/vincular un cliente.
-- La Edge Function `crear-cliente` (no versionada) inserta clientes con
-- auth_user_id; este trigger crea el perfil 'cliente' para que la RLS funcione
-- sin cambiar esa función. No pisa un perfil existente (p. ej. un admin).
create or replace function public.clientes_sync_perfil()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.auth_user_id is not null then
    insert into public.perfiles (user_id, rol, cliente_id)
    values (new.auth_user_id, 'cliente', new.id)
    on conflict (user_id) do nothing;
  end if;
  return null;
end
$$;
revoke all on function public.clientes_sync_perfil() from public, anon, authenticated;

drop trigger if exists trg_clientes_sync_perfil on public.clientes;
create trigger trg_clientes_sync_perfil
  after insert or update of auth_user_id on public.clientes
  for each row execute function public.clientes_sync_perfil();

