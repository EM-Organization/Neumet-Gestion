-- 8.1 get_unregistered_devices()
-- Forma de salida deducida de app.js:1786-1806 y de la fixture: device_id,
-- last_seen, total_meds. [ASUNCIÓN] tipos.
-- Un dispositivo "no registrado" = MAC con mediciones y sin fila en dispositivos.
create or replace function public.get_unregistered_devices()
returns table (device_id text, last_seen timestamptz, total_meds bigint)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if not public.is_admin() then
    raise exception 'permiso denegado' using errcode = '42501';
  end if;
  return query
    select m.device_id, max(m.created_at), count(*)::bigint
    from public.mediciones m
    where m.device_id is not null
      and not exists (select 1 from public.dispositivos d where d.mac_address = m.device_id)
    group by m.device_id
    order by max(m.created_at) desc;
end
$$;

-- 8.2 asignar_dispositivo_a_cliente(p_mac, p_cliente_id, p_nombre)
-- Parámetros: app.js:1917-1921. Resultado: app.js:1924-1925
-- ({vehiculos_creados, mediciones_vinculadas}); dispositivo_id es añadido.
-- Comportamiento: README "Fase 2". Una sola transacción (la de la llamada).
-- [ASUNCIÓN] identidad del vehículo en una medición = patente_raw (normalizada)
--   si existe, si no numero_raw. Mediciones sin ninguna de las dos solo reciben
--   cliente_id. [ASUNCIÓN] vehículos nuevos: nombre = patente o 'Nº <numero>',
--   tipo_ruedas = 16 si alguna posición > 10, si no 10.
create or replace function public.asignar_dispositivo_a_cliente(
  p_mac        text,
  p_cliente_id bigint,
  p_nombre     text default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_mac        text := upper(replace(btrim(coalesce(p_mac, '')), '-', ':'));
  v_disp_id    bigint;
  v_creados    integer := 0;
  v_vinculadas integer := 0;
  v_n          integer;
  r            record;
  v_veh_id     bigint;
begin
  if not public.is_admin() then
    raise exception 'permiso denegado' using errcode = '42501';
  end if;
  if v_mac !~ '^([0-9A-F]{2}:){5}[0-9A-F]{2}$' then
    raise exception 'MAC invalida: %', p_mac using errcode = '22023';
  end if;
  if not exists (select 1 from public.clientes c where c.id = p_cliente_id and c.deleted_at is null) then
    raise exception 'cliente inexistente: %', p_cliente_id using errcode = '23503';
  end if;

  -- Serializa asignaciones concurrentes de la misma MAC.
  perform pg_advisory_xact_lock(hashtextextended(v_mac, 0));

  -- Falla con unique_violation (23505) si la MAC ya está registrada.
  insert into public.dispositivos (mac_address, nombre, cliente_id)
  values (v_mac, nullif(btrim(coalesce(p_nombre, '')), ''), p_cliente_id)
  returning id into v_disp_id;

  -- Un grupo por identidad de vehículo presente en las mediciones del dispositivo.
  for r in
    select public.normalizar_patente(m.patente_raw)       as pn,
           nullif(btrim(coalesce(m.numero_raw, '')), '')  as nr,
           max(m.posicion)                                as max_pos
    from public.mediciones m
    where m.device_id = v_mac
      and (public.normalizar_patente(m.patente_raw) is not null
           or nullif(btrim(coalesce(m.numero_raw, '')), '') is not null)
    group by 1, 2
  loop
    v_veh_id := null;
    if r.pn is not null then
      select v.id into v_veh_id from public.vehiculos v
      where v.cliente_id = p_cliente_id and v.patente_norm = r.pn;
    end if;
    if v_veh_id is null and r.nr is not null then
      select v.id into v_veh_id from public.vehiculos v
      where v.cliente_id = p_cliente_id and v.numero = r.nr;
    end if;

    if v_veh_id is null then
      insert into public.vehiculos (cliente_id, nombre, patente, numero, tipo_ruedas)
      values (
        p_cliente_id,
        coalesce(r.pn, 'Nº ' || r.nr),
        r.pn,
        r.nr,
        case when r.max_pos > 10 then 16 else 10 end
      )
      returning id into v_veh_id;
      v_creados := v_creados + 1;
    end if;

    update public.mediciones m
       set vehiculo_id = v_veh_id, cliente_id = p_cliente_id
     where m.device_id = v_mac
       and public.normalizar_patente(m.patente_raw) is not distinct from r.pn
       and nullif(btrim(coalesce(m.numero_raw, '')), '') is not distinct from r.nr
       and (m.vehiculo_id is distinct from v_veh_id or m.cliente_id is distinct from p_cliente_id);
    get diagnostics v_n = row_count;
    v_vinculadas := v_vinculadas + v_n;
  end loop;

  -- Mediciones sin identidad de vehículo: solo se asigna el cliente.
  update public.mediciones m
     set cliente_id = p_cliente_id
   where m.device_id = v_mac
     and m.cliente_id is distinct from p_cliente_id
     and public.normalizar_patente(m.patente_raw) is null
     and nullif(btrim(coalesce(m.numero_raw, '')), '') is null;
  get diagnostics v_n = row_count;
  v_vinculadas := v_vinculadas + v_n;

  return jsonb_build_object(
    'dispositivo_id',       v_disp_id,
    'vehiculos_creados',    v_creados,
    'mediciones_vinculadas', v_vinculadas
  );
end
$$;

revoke all on function public.get_unregistered_devices()                         from public, anon;
revoke all on function public.asignar_dispositivo_a_cliente(text, bigint, text)  from public, anon;
grant execute on function public.get_unregistered_devices()                        to authenticated;
grant execute on function public.asignar_dispositivo_a_cliente(text, bigint, text) to authenticated;

commit;

