-- Normaliza una patente: mayúsculas y sin espacios en blanco (docs/07 §3.2).
-- IMMUTABLE para poder usarla en una columna generada.
create or replace function public.normalizar_patente(p text)
returns text
language sql
immutable
parallel safe
set search_path = ''
as $$
  select nullif(upper(regexp_replace(coalesce(p, ''), '\s+', '', 'g')), '')
$$;

