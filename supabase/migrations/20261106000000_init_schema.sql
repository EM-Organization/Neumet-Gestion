-- 6.2 Auditoría genérica (SECURITY DEFINER: escribe aunque el actor no tenga INSERT)
create or replace function public.audit_row()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := auth.uid();
  v_rol text;
  v_old jsonb := case when tg_op in ('UPDATE','DELETE') then to_jsonb(old) end;
  v_new jsonb := case when tg_op in ('INSERT','UPDATE') then to_jsonb(new) end;
begin
  if v_uid is not null then
    select p.rol into v_rol from public.perfiles p where p.user_id = v_uid;
  end if;
  insert into public.audit_log (actor_id, actor_rol, accion, entidad, entidad_id, antes, despues)
  values (
    v_uid,
    coalesce(v_rol, case when v_uid is null then 'sistema' else 'sin_perfil' end),
    tg_op,
    tg_table_name,
    coalesce(v_new ->> 'id', v_old ->> 'id'),
    v_old,
    v_new
  );
  return null; -- AFTER trigger
end
$$;
revoke all on function public.audit_row() from public, anon, authenticated;

