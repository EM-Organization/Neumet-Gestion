create table if not exists public.eventos_neumatico (
  id               bigint generated by default as identity primary key,
  cliente_id       bigint not null references public.clientes (id) on delete restrict,
  vehiculo_id      bigint references public.vehiculos (id) on delete restrict,
  -- SET NULL: el evento sobrevive a la fila del neumático (idneumatico lo identifica).
  neumatico_id     bigint references public.neumaticos (id) on delete set null,
  idneumatico      text,
  tipo             text not null check (tipo in
                     ('montaje','desmontaje','rotacion','reparacion','reencauche','baja','inspeccion')),
  posicion_origen  smallint,
  posicion_destino smallint,
  odometro_km      integer check (odometro_km is null or odometro_km >= 0),
  costo            numeric(12,2) check (costo is null or costo >= 0),
  notas            text,
  created_by       uuid default auth.uid(),
  created_at       timestamptz not null default now()
);

create index if not exists eventos_neumatico_cliente_idx  on public.eventos_neumatico (cliente_id);
create index if not exists eventos_neumatico_vehiculo_idx on public.eventos_neumatico (vehiculo_id) where vehiculo_id is not null;
