-- 5.1 Última medición por (vehículo, posición)
create or replace view public.v_ultima_medicion
with (security_invoker = true) as
select distinct on (m.vehiculo_id, m.posicion)
  v.cliente_id,
  m.vehiculo_id,
  m.posicion,
  m.id          as medicion_id,
  m.idneumatico,
  m.mm1, m.mm2, m.mm3,
  m.promedio,
  m.odometro_km,
  m.device_id,
  m.created_at
from public.mediciones m
join public.vehiculos v on v.id = m.vehiculo_id
order by m.vehiculo_id, m.posicion, m.created_at desc, m.id desc;

-- 5.2 Estado por neumático montado / posición medida
-- Posiciones = filas de neumaticos + posiciones con mediciones sin fila en
-- neumaticos. Se excluyen vehículos inactivos, clientes eliminados y neumáticos
-- que no están montados (almacenado/reparación/baja).
create or replace view public.v_estado_neumaticos
with (security_invoker = true) as
with tasa as (
  select v.cliente_id, m.vehiculo_id, m.posicion,
         count(*)                                              as n_mediciones_90d,
         count(distinct (m.created_at at time zone 'UTC')::date) as n_fechas,
         regr_slope(m.promedio::float8, extract(epoch from m.created_at)) as slope_mm_s
  from public.mediciones m
  join public.vehiculos v on v.id = m.vehiculo_id
  where m.created_at >= now() - interval '90 days'
  group by v.cliente_id, m.vehiculo_id, m.posicion
),
slots as (
  select n.vehiculo_id, n.posicion, n.id as neumatico_id, n.idneumatico as neum_idneumatico,
         n.marca, n.modelo, n.vida, n.estado as estado_montaje
  from public.neumaticos n
  union all
  select u.vehiculo_id, u.posicion, null::bigint, null::text, null::text, null::text, null::smallint, null::text
  from public.v_ultima_medicion u
  where not exists (select 1 from public.neumaticos n
                    where n.vehiculo_id = u.vehiculo_id and n.posicion = u.posicion)
),
b as (
  select
    v.cliente_id, s.vehiculo_id, v.nombre as vehiculo_nombre, v.patente, s.posicion,
    s.neumatico_id,
    coalesce(u.idneumatico, s.neum_idneumatico) as idneumatico,
    s.marca, s.modelo, s.vida,
    coalesce(s.estado_montaje, 'montado') as estado_montaje,
    u.mm1, u.mm2, u.mm3, u.promedio, u.odometro_km,
    u.created_at as ultima_medicion_at,
    case when u.created_at is null then null
         else floor(extract(epoch from now() - u.created_at) / 86400)::integer end as dias_desde_medicion,
    case when u.promedio is null               then 'sin_datos'
         when u.promedio < c.umbral_critico_mm then 'critico'
         when u.promedio < c.umbral_bajo_mm    then 'bajo'
         else 'ok' end as estado,
    case when u.created_at is null then s.neumatico_id is not null
         else u.created_at < now() - make_interval(days => c.dias_sin_medir_alerta) end as sin_medir,
    case when u.promedio is null then null
         else greatest(u.mm1, u.mm2, u.mm3) - least(u.mm1, u.mm2, u.mm3) end as diferencia_huellas_mm,
    coalesce(greatest(u.mm1, u.mm2, u.mm3) - least(u.mm1, u.mm2, u.mm3) > c.irregularidad_mm, false)
      as desgaste_irregular,
    coalesce(t.n_mediciones_90d, 0) as n_mediciones_90d,
    case when t.n_fechas >= 2 and t.slope_mm_s is not null
         then round((-t.slope_mm_s * 604800)::numeric, 3) end as tasa_mm_semana,
    c.umbral_bajo_mm, c.umbral_critico_mm, c.umbral_retiro_mm, c.dias_sin_medir_alerta
  from slots s
  join public.vehiculos v on v.id = s.vehiculo_id and v.activo
  join public.clientes  c on c.id = v.cliente_id and c.deleted_at is null
  left join public.v_ultima_medicion u on u.vehiculo_id = s.vehiculo_id and u.posicion = s.posicion
  left join tasa t on t.vehiculo_id = s.vehiculo_id and t.posicion = s.posicion
  where coalesce(s.estado_montaje, 'montado') = 'montado'
)
select b.*,
  case when b.tasa_mm_semana > 0 and b.promedio is not null
       then round(greatest(b.promedio - b.umbral_critico_mm, 0) / b.tasa_mm_semana, 2) end as semanas_hasta_critico,
  case when b.tasa_mm_semana > 0 and b.promedio is not null
       then round(greatest(b.promedio - b.umbral_retiro_mm, 0) / b.tasa_mm_semana, 2) end  as semanas_hasta_retiro
from b;

-- 5.3 Alertas activas (una fila por alerta)
create or replace view public.v_alertas
with (security_invoker = true) as
select cliente_id, vehiculo_id, vehiculo_nombre, patente, posicion, neumatico_id, idneumatico,
       tipo, severidad, valor, mensaje, ultima_medicion_at
from (
  select e.*, 'critico'::text as tipo, 3 as severidad, e.promedio as valor,
         format('Neumático crítico: %s mm (límite %s mm)', e.promedio, e.umbral_critico_mm) as mensaje
  from public.v_estado_neumaticos e where e.estado = 'critico'
  union all
  select e.*, 'bajo', 2, e.promedio,
         format('Desgaste bajo: %s mm (límite %s mm)', e.promedio, e.umbral_bajo_mm)
  from public.v_estado_neumaticos e where e.estado = 'bajo'
  union all
  select e.*, 'cruza_critico_pronto', 2, e.semanas_hasta_critico,
         format('Cruzará el nivel crítico en ~%s semanas', e.semanas_hasta_critico)
  from public.v_estado_neumaticos e
  where e.estado in ('ok', 'bajo') and e.semanas_hasta_critico <= 4
  union all
  select e.*, 'desgaste_irregular', 2, e.diferencia_huellas_mm,
         format('Desgaste irregular: %s mm entre huellas (máx. %s mm)', e.diferencia_huellas_mm,
                (select c.irregularidad_mm from public.clientes c where c.id = e.cliente_id))
  from public.v_estado_neumaticos e where e.desgaste_irregular
  union all
  select e.*, 'sin_medir', 1, e.dias_desde_medicion,
         case when e.ultima_medicion_at is null then 'Neumático montado sin ninguna medición'
              else format('Sin medir hace %s días (alerta a los %s)', e.dias_desde_medicion, e.dias_sin_medir_alerta) end
  from public.v_estado_neumaticos e where e.sin_medir
) a;

-- 5.4 Resumen de flota por cliente
create or replace view public.v_resumen_flota_cliente
with (security_invoker = true) as
select
  c.id as cliente_id,
  c.nombre,
  coalesce(veh.n, 0)         as n_vehiculos_activos,
  coalesce(e.n_con_datos, 0) as n_neumaticos_con_datos,
  coalesce(e.n_ok, 0)        as n_ok,
  coalesce(e.n_bajo, 0)      as n_bajo,
  coalesce(e.n_critico, 0)   as n_critico,
  coalesce(e.n_sin_datos, 0) as n_sin_datos,
  coalesce(a.sev1, 0)        as n_alertas_sev1,
  coalesce(a.sev2, 0)        as n_alertas_sev2,
  coalesce(a.sev3, 0)        as n_alertas_sev3,
  mm.ultima_medicion_at
from public.clientes c
left join (select cliente_id, count(*) as n from public.vehiculos where activo group by cliente_id) veh
       on veh.cliente_id = c.id
left join (select cliente_id,
                  count(*) filter (where estado <> 'sin_datos') as n_con_datos,
                  count(*) filter (where estado = 'ok')         as n_ok,
                  count(*) filter (where estado = 'bajo')       as n_bajo,
                  count(*) filter (where estado = 'critico')    as n_critico,
                  count(*) filter (where estado = 'sin_datos')  as n_sin_datos
           from public.v_estado_neumaticos group by cliente_id) e on e.cliente_id = c.id
left join (select cliente_id,
                  count(*) filter (where severidad = 1) as sev1,
                  count(*) filter (where severidad = 2) as sev2,
                  count(*) filter (where severidad = 3) as sev3
           from public.v_alertas group by cliente_id) a on a.cliente_id = c.id
left join (select cliente_id, max(created_at) as ultima_medicion_at
           from public.mediciones where cliente_id is not null group by cliente_id) mm
       on mm.cliente_id = c.id
where c.deleted_at is null;

-- 5.5 Salud de dispositivos
create or replace view public.v_salud_dispositivos
with (security_invoker = true) as
select
  d.id as dispositivo_id,
  d.cliente_id,
  d.mac_address,
  d.nombre,
  d.activo,
  s.ultima_actividad_at,
  coalesce(s.total_mediciones, 0) as total_mediciones,
  case when s.ultima_actividad_at is null then null
       else floor(extract(epoch from now() - s.ultima_actividad_at) / 86400)::integer end as dias_sin_actividad,
  case when s.ultima_actividad_at is null                      then 'nunca'
       when now() - s.ultima_actividad_at < interval '8 days'  then 'activo'        -- <= 7 días enteros
       when now() - s.ultima_actividad_at < interval '31 days' then 'sin_actividad'  -- <= 30 días enteros
       else 'caido' end as estado
from public.dispositivos d
left join lateral (
  select max(m.created_at) as ultima_actividad_at, count(*) as total_mediciones
  from public.mediciones m where m.device_id = d.mac_address
) s on true;

revoke all on public.v_ultima_medicion, public.v_estado_neumaticos, public.v_alertas,
  public.v_resumen_flota_cliente, public.v_salud_dispositivos from public, anon;
grant select on public.v_ultima_medicion, public.v_estado_neumaticos, public.v_alertas,
  public.v_resumen_flota_cliente, public.v_salud_dispositivos to authenticated;

-- -----------------------------------------------------------------------------
-- 6. RPC: eliminación suave de cliente (el DELETE directo sigue fallando: RESTRICT)
-- -----------------------------------------------------------------------------
create or replace function public.cliente_eliminar_suave(p_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_veh integer;
  v_dis integer;
begin
  if not public.is_admin() then
    raise exception 'permiso denegado' using errcode = '42501';
  end if;
  if not exists (select 1 from public.clientes c where c.id = p_id) then
    raise exception 'cliente inexistente: %', p_id using errcode = '23503';
  end if;

  update public.clientes set deleted_at = coalesce(deleted_at, now()) where id = p_id;
  update public.vehiculos set activo = false where cliente_id = p_id and activo;
  get diagnostics v_veh = row_count;
  update public.dispositivos set activo = false where cliente_id = p_id and activo;
  get diagnostics v_dis = row_count;

  return jsonb_build_object('cliente_id', p_id, 'vehiculos_desactivados', v_veh,
                            'dispositivos_desactivados', v_dis);
end
$$;

revoke all on function public.cliente_eliminar_suave(bigint) from public, anon;
grant execute on function public.cliente_eliminar_suave(bigint) to authenticated;
