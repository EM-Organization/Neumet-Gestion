-- -----------------------------------------------------------------------------
-- 1. Umbrales por cliente
-- -----------------------------------------------------------------------------
-- Semáforo (igual que WEAR/wearStatus de app.js): promedio < critico => critico;
-- < bajo => bajo; si no ok. Por eso 5.0 es 'bajo' y 8.0 es 'ok'.
alter table public.clientes
  add column if not exists umbral_bajo_mm          numeric(4,1) not null default 8,
  add column if not exists umbral_critico_mm       numeric(4,1) not null default 5,
  add column if not exists umbral_retiro_mm        numeric(4,1) not null default 3,
  add column if not exists dias_sin_medir_alerta   integer      not null default 30,
  add column if not exists irregularidad_mm        numeric(3,1) not null default 2;

alter table public.clientes drop constraint if exists clientes_umbrales_ck;
alter table public.clientes add constraint clientes_umbrales_ck check (
  umbral_retiro_mm > 0
  and umbral_retiro_mm < umbral_critico_mm
  and umbral_critico_mm < umbral_bajo_mm
  and dias_sin_medir_alerta > 0
  and irregularidad_mm > 0
);

