-- Configuración del cliente: umbral crítico (mm) e histéresis (mm). Solo admin o perfil de cliente GLOBAL; el de
-- sucursal no edita umbrales. El trigger trg_alerta_clientes reevalúa la flota del cliente (abre y resuelve).
-- Parámetro null = no cambia. Mantiene retiro < crítico < bajo (clientes_umbrales_ck).
create or replace function public.alerta_configurar(
  p_cliente_id         bigint,
  p_umbral_critico_mm  numeric default null,
  p_histeresis_mm      numeric default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid     uuid := auth.uid();
  v_perf    public.perfiles%rowtype;
  v_cli_id  bigint;
  v_c       public.clientes%rowtype;
  v_abiertas bigint;
begin
  if v_uid is null then
    raise exception 'permiso denegado' using errcode = '42501';
  end if;
  if public.is_admin() then
    if p_cliente_id is null then
      raise exception 'parámetros obligatorios' using errcode = '22004';
    end if;
    v_cli_id := p_cliente_id;
  else
    select * into v_perf from public.perfiles p where p.user_id = v_uid and p.rol = 'cliente';
    if not found or v_perf.cliente_id is null or v_perf.sucursal_id is not null
       or (p_cliente_id is not null and p_cliente_id <> v_perf.cliente_id) then
      raise exception 'permiso denegado' using errcode = '42501';
    end if;
    v_cli_id := v_perf.cliente_id;
  end if;

  select * into v_c from public.clientes c where c.id = v_cli_id and c.deleted_at is null for update;
  if not found then
    raise exception 'permiso denegado' using errcode = '42501';
  end if;

  if p_umbral_critico_mm is null and p_histeresis_mm is null then
    raise exception 'parámetros obligatorios' using errcode = '22004';
  end if;
  if p_umbral_critico_mm is not null then
    if p_umbral_critico_mm <> round(p_umbral_critico_mm, 1) then
      raise exception 'el umbral admite un decimal' using errcode = '22023';
    end if;
    if p_umbral_critico_mm <= v_c.umbral_retiro_mm or p_umbral_critico_mm >= v_c.umbral_bajo_mm then
      raise exception 'el nivel crítico debe quedar entre el de retiro (% mm) y el de desgaste bajo (% mm)',
        v_c.umbral_retiro_mm, v_c.umbral_bajo_mm using errcode = '23514';
    end if;
  end if;
  if p_histeresis_mm is not null then
    if p_histeresis_mm <> round(p_histeresis_mm, 1) or p_histeresis_mm < 0 or p_histeresis_mm > 3 then
      raise exception 'la histéresis va de 0 a 3 mm, con un decimal' using errcode = '23514';
    end if;
  end if;

  update public.clientes
     set umbral_critico_mm = coalesce(p_umbral_critico_mm, umbral_critico_mm),
         alerta_histeresis_mm = coalesce(p_histeresis_mm, alerta_histeresis_mm)
   where id = v_c.id;

  select count(*) into v_abiertas from public.alertas a where a.cliente_id = v_c.id and a.estado <> 'resuelta';
  select * into v_c from public.clientes c where c.id = v_c.id;
  return jsonb_build_object('cliente_id', v_c.id, 'umbral_critico_mm', v_c.umbral_critico_mm,
                            'histeresis_mm', v_c.alerta_histeresis_mm, 'alertas_abiertas', v_abiertas);
end
$$;
revoke all on function public.alerta_configurar(bigint, numeric, numeric) from public, anon;
grant execute on function public.alerta_configurar(bigint, numeric, numeric) to authenticated;

-- -----------------------------------------------------------------------------
-- 6. v_alertas: solo la alerta crítica con estado (mismas columnas y tipos; columnas nuevas al final)
-- -----------------------------------------------------------------------------
-- security_invoker: hereda la RLS de alertas y de vehiculos. v_resumen_flota_cliente la sigue leyendo
-- (n_alertas_sev3 = alertas críticas abiertas o reconocidas; sev1 y sev2 quedan en 0).
create or replace view public.v_alertas
with (security_invoker = true) as
select a.cliente_id, a.vehiculo_id, v.nombre as vehiculo_nombre, v.patente, a.posicion, a.neumatico_id, a.idneumatico,
       a.tipo, 3 as severidad, a.mm_actual::numeric as valor,
       format('Neumático crítico: %s mm (límite %s mm)', a.mm_actual, a.umbral_mm) as mensaje,
       a.ultima_medicion_at,
       a.id as alerta_id, a.estado, a.umbral_mm, a.mm_apertura, a.mm_minimo, a.abierta_at, a.reconocida_at,
       a.silenciada_hasta, a.veces_reabierta
from public.alertas a
join public.vehiculos v on v.id = a.vehiculo_id
join public.clientes c on c.id = a.cliente_id and c.deleted_at is null   -- cliente eliminado: sin alertas
where a.estado <> 'resuelta';

revoke all on public.v_alertas from public, anon;
grant select on public.v_alertas to authenticated;

