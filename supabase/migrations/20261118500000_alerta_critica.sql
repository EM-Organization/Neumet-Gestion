create table if not exists public.alertas (
  id                  bigint generated by default as identity primary key,
  cliente_id          bigint not null references public.clientes (id) on delete cascade,
  vehiculo_id         bigint not null references public.vehiculos (id) on delete cascade,
  neumatico_id        bigint not null references public.neumaticos (id) on delete cascade,
  posicion            smallint,
  idneumatico         text,
  tipo                text not null default 'critico' check (tipo = 'critico'),
  estado              text not null default 'abierta' check (estado in ('abierta', 'reconocida', 'resuelta')),
  umbral_mm           numeric(4,1) not null,            -- umbral vigente (se actualiza si el cliente lo cambia)
  mm_apertura         numeric(5,2) not null,
  mm_minimo           numeric(5,2) not null,
  mm_actual           numeric(5,2) not null,
  ultima_medicion_at  timestamptz,
  abierta_at          timestamptz not null default now(),
  reconocida_at       timestamptz,
  reconocida_por      uuid,
  nota_reconocida     text check (nota_reconocida is null or length(nota_reconocida) <= 200),
  silenciada_hasta    timestamptz,
  silencio_motivo     text check (silencio_motivo is null or length(silencio_motivo) <= 200),
  silenciada_por      uuid,
  resuelta_at         timestamptz,
  resuelta_motivo     text check (resuelta_motivo in ('recuperada', 'cambio', 'baja', 'manual', 'sin_datos')),
  resuelta_por        uuid,
  nota_resolucion     text check (nota_resolucion is null or length(nota_resolucion) <= 200),
  veces_reabierta     integer not null default 0,
  updated_at          timestamptz not null default now(),
  constraint alertas_resuelta_ck check ((estado = 'resuelta') = (resuelta_at is not null))
);
