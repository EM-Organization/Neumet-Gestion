-- =============================================================================
-- NEUMET · Alerta única «Neumático crítico» con estado (hoja de ruta F7, docs/15 sección B, etapa 1)
-- =============================================================================
-- Requiere 20261106000000_init_schema.sql (audit_row, is_admin, perfiles), 20261106020000_producto_vistas.sql
-- (clientes.umbral_*, v_resumen_flota_cliente), 20261107020000_seccionales.sql (current_sucursal_id),
-- 20261108000000_cambio_neumatico.sql (neumatico_autorizar_vehiculo) y 20261116000000_calidad_datos.sql
-- (v_estado_neumaticos vigente, mediciones.calidad).
-- Sin begin/commit: la herramienta que aplica la migración ya la envuelve. Idempotente.
--
-- Decisión de producto (docs/15 B.2): un solo tipo de alerta, «crítico». Un neumático montado está en estado crítico
-- cuando su promedio de mm es menor que el umbral crítico de su cliente (clientes.umbral_critico_mm, editable por el
-- propio cliente con alerta_configurar). «Bajo», «cruza el crítico pronto», «desgaste irregular» y «sin medir» dejan
-- de ser alertas: siguen disponibles como indicadores en v_estado_neumaticos (estado, semanas_hasta_critico,
-- desgaste_irregular, sin_medir), sin estado ni notificación.
--
-- Modelo (docs/15 B.4, alternativa 2): tabla `alertas` con estado (abierta, reconocida, resuelta).
--   * Histéresis: se abre con promedio < U y se resuelve con promedio >= U + histéresis (clientes.alerta_histeresis_mm,
--     0,5 mm por defecto). Entre ambos valores la alerta sigue como estaba.
--   * Deduplicación: índice único parcial, a lo sumo una alerta no resuelta por neumático. La alerta sigue al neumático
--     (rotar no crea otra); un neumático nuevo en la posición es otro neumático.
--   * Reapertura: si una alerta resuelta por «recuperada» vuelve a cruzar el umbral dentro de 7 días se reabre la misma
--     fila (veces_reabierta + 1).
--   * Resolución: automática (recuperada, cambio, baja, sin_datos si todas sus mediciones quedaron invalidadas) o
--     manual con nota. Una resolución manual con el neumático aún bajo el umbral no bloquea: la siguiente medición
--     abre una alerta nueva.
--   * Dato no medido: nulo, nunca alerta (un neumático sin promedio no abre alerta).
--
-- Quién evalúa: alerta_sincronizar(cliente, neumáticos) es la única función de evaluación; la llaman triggers de
-- mediciones (insert y update, nivel sentencia con tablas de transición: un lote de la API = una evaluación),
-- neumaticos (estado, posición, vehículo) y clientes (umbral crítico o histéresis). Un fallo de la evaluación no
-- bloquea la escritura de origen (la ingesta de mediciones es crítica): queda como WARNING y la siguiente
-- evaluación lo corrige.
--
-- Seguridad:
--   * RLS como perímetro: lectura con la misma regla que vehiculos (admin; cliente de su cliente; perfil de
--     sucursal solo vehículos de su sucursal). Sin INSERT/UPDATE/DELETE para authenticated.
--   * Transiciones por RPC SECURITY DEFINER con search_path vacío; la autorización se verifica DENTRO con
--     neumatico_autorizar_vehiculo (nunca por parámetros). Todo rechazo es 42501; el rol api, sin perfil y anon, nada.
--   * alerta_configurar: solo admin o perfil de cliente GLOBAL (el de sucursal no edita umbrales).
--   * Auditoría: trg_audit_alertas (audit_row) registra apertura, reconocimiento, silencio y resolución con el actor.
-- Alcance de esta etapa: sin anulaciones por eje, posición ni marca/modelo, sin destinatarios ni correo (docs/15 B.5,
-- etapas 2 y 3).
-- =============================================================================

