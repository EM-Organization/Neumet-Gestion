-- 4.1 mediciones (insert y update, nivel sentencia): los neumáticos afectados, por idneumatico o por posición montada.
create or replace function public.trg_alerta_mediciones()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  r record;
begin
  begin
    for r in
      select x.cliente_id, array_agg(distinct x.id) as ids
        from (select n.cliente_id, n.id
                from (select distinct idneumatico from nuevas where idneumatico is not null) m
                join public.neumaticos n on n.idneumatico = m.idneumatico
              union
              select n.cliente_id, n.id
                from (select distinct vehiculo_id, posicion from nuevas
                       where idneumatico is null and vehiculo_id is not null) m
                join public.neumaticos n on n.vehiculo_id = m.vehiculo_id and n.posicion = m.posicion
                                        and n.estado = 'montado') x
       group by x.cliente_id
    loop
      perform public.alerta_sincronizar(r.cliente_id, r.ids);
    end loop;
  exception when others then
    raise warning 'alerta_sincronizar (mediciones): % [%]', sqlerrm, sqlstate;
  end;
  return null;
end
$$;
revoke all on function public.trg_alerta_mediciones() from public, anon, authenticated;

drop trigger if exists trg_alerta_mediciones_ins on public.mediciones;
create trigger trg_alerta_mediciones_ins after insert on public.mediciones
  referencing new table as nuevas
  for each statement execute function public.trg_alerta_mediciones();
drop trigger if exists trg_alerta_mediciones_upd on public.mediciones;
create trigger trg_alerta_mediciones_upd after update on public.mediciones
  referencing new table as nuevas
  for each statement execute function public.trg_alerta_mediciones();

-- 4.2 neumaticos: cambio de estado, posición o vehículo (rotar, cambiar, montar, retirar, dar de baja).
create or replace function public.trg_alerta_neumaticos()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  begin
    perform public.alerta_sincronizar(new.cliente_id, array[new.id]);
  exception when others then
    raise warning 'alerta_sincronizar (neumaticos): % [%]', sqlerrm, sqlstate;
  end;
  return null;
end
$$;
revoke all on function public.trg_alerta_neumaticos() from public, anon, authenticated;

drop trigger if exists trg_alerta_neumaticos_ins on public.neumaticos;
create trigger trg_alerta_neumaticos_ins after insert on public.neumaticos
  for each row execute function public.trg_alerta_neumaticos();
drop trigger if exists trg_alerta_neumaticos_upd on public.neumaticos;
create trigger trg_alerta_neumaticos_upd after update of estado, posicion, vehiculo_id, idneumatico on public.neumaticos
  for each row
  when (old.estado is distinct from new.estado or old.posicion is distinct from new.posicion
        or old.vehiculo_id is distinct from new.vehiculo_id or old.idneumatico is distinct from new.idneumatico)
  execute function public.trg_alerta_neumaticos();

