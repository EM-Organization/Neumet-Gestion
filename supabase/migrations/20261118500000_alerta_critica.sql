-- -----------------------------------------------------------------------------
-- 5. RPC de transición (SECURITY DEFINER, autorización interna, 42501 uniforme)
-- -----------------------------------------------------------------------------
-- Carga y bloquea la alerta tras autorizar sobre su vehículo. Inexistente o ajena responde igual (42501) para no
-- revelar existencia; solo el admin distingue «inexistente» (P0002), como neumatico_autorizar_vehiculo.
create or replace function public.alerta_cargar(p_alerta_id bigint)
returns public.alertas
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_a public.alertas%rowtype;
begin
  if auth.uid() is null then
    raise exception 'permiso denegado' using errcode = '42501';
  end if;
  if p_alerta_id is null then
    raise exception 'parámetros obligatorios' using errcode = '22004';
  end if;
  select * into v_a from public.alertas where id = p_alerta_id;
  if not found then
    if public.is_admin() then
      raise exception 'alerta inexistente' using errcode = 'P0002';
    end if;
    raise exception 'permiso denegado' using errcode = '42501';
  end if;
  -- Autoriza y bloquea el vehículo (serializa con cambios y rotaciones). Lanza 42501 si no corresponde.
  perform 1 from public.neumatico_autorizar_vehiculo(v_a.vehiculo_id);
  -- Relee con bloqueo: el vehículo pudo cambiar mientras tanto (la alerta sigue al neumático).
  select * into v_a from public.alertas where id = p_alerta_id for update;
  if not found then
    raise exception 'permiso denegado' using errcode = '42501';
  end if;
  return v_a;
end
$$;
revoke all on function public.alerta_cargar(bigint) from public, anon, authenticated;

create or replace function public.alerta_reconocer(p_alerta_id bigint, p_nota text default null)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_a    public.alertas%rowtype;
  v_nota text := nullif(btrim(coalesce(p_nota, '')), '');
begin
  v_a := public.alerta_cargar(p_alerta_id);
  if v_nota is not null and length(v_nota) > 200 then
    raise exception 'nota demasiado larga (máx. 200)' using errcode = '22023';
  end if;
  if v_a.estado = 'resuelta' then
    raise exception 'la alerta ya está resuelta' using errcode = '55000';
  end if;
  if v_a.estado = 'reconocida' then
    return jsonb_build_object('id', v_a.id, 'estado', 'reconocida', 'cambiado', false);
  end if;
  update public.alertas
     set estado = 'reconocida', reconocida_at = now(), reconocida_por = auth.uid(), nota_reconocida = v_nota,
         updated_at = now()
   where id = v_a.id;
  return jsonb_build_object('id', v_a.id, 'estado', 'reconocida', 'cambiado', true);
end
$$;
revoke all on function public.alerta_reconocer(bigint, text) from public, anon;
grant execute on function public.alerta_reconocer(bigint, text) to authenticated;

-- Silencia hasta una fecha (máximo 90 días) con motivo; p_hasta null quita el silencio. La alerta sigue abierta.
create or replace function public.alerta_silenciar(p_alerta_id bigint, p_hasta timestamptz, p_motivo text default null)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_a      public.alertas%rowtype;
  v_motivo text := nullif(btrim(coalesce(p_motivo, '')), '');
begin
  v_a := public.alerta_cargar(p_alerta_id);
  if v_motivo is not null and length(v_motivo) > 200 then
    raise exception 'motivo demasiado largo (máx. 200)' using errcode = '22023';
  end if;
  if v_a.estado = 'resuelta' then
    raise exception 'la alerta ya está resuelta' using errcode = '55000';
  end if;
  if p_hasta is null then
    update public.alertas
       set silenciada_hasta = null, silencio_motivo = null, silenciada_por = null, updated_at = now()
     where id = v_a.id;
    return jsonb_build_object('id', v_a.id, 'estado', v_a.estado, 'silenciada_hasta', null);
  end if;
  if p_hasta <= now() or p_hasta > now() + interval '90 days' then
    raise exception 'la fecha de silencio debe ser futura y de hasta 90 días' using errcode = '22023';
  end if;
  update public.alertas
     set silenciada_hasta = p_hasta, silencio_motivo = v_motivo, silenciada_por = auth.uid(), updated_at = now()
   where id = v_a.id;
  return jsonb_build_object('id', v_a.id, 'estado', v_a.estado, 'silenciada_hasta', p_hasta);
end
$$;
revoke all on function public.alerta_silenciar(bigint, timestamptz, text) from public, anon;
grant execute on function public.alerta_silenciar(bigint, timestamptz, text) to authenticated;

create or replace function public.alerta_resolver(p_alerta_id bigint, p_nota text)
