  using (cliente_id = (select public.current_cliente_id())
         and (select public.current_sucursal_id()) is null);

-- -----------------------------------------------------------------------------
-- 3. costos_visibles(): quién puede ver costos (interno de la vista)
-- -----------------------------------------------------------------------------
-- admin y perfil global de un cliente. El perfil de sucursal, api, sin perfil y anon: false. Un rol que ya omite la
-- RLS (service_role, dueño, superusuario) ve todo, como en las tablas.
create or replace function public.costos_visibles()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select case
    when coalesce(current_setting('role', true), 'none') in ('authenticated', 'anon') then
      exists (select 1 from public.perfiles p
               where p.user_id = (select auth.uid())
                 and (p.rol = 'admin' or (p.rol = 'cliente' and p.cliente_id is not null and p.sucursal_id is null)))
    else true
  end
$$;
revoke all on function public.costos_visibles() from public, anon;
grant execute on function public.costos_visibles() to authenticated;

-- -----------------------------------------------------------------------------
-- 4. RPC costo_registrar y costo_eliminar
-- -----------------------------------------------------------------------------
-- Autorización: admin, o perfil GLOBAL del cliente dueño de la cubierta (sucursal_autorizar_gestion). Sucursal, api,
-- sin perfil, otro cliente y una cubierta inexistente son indistinguibles para un no-admin: 42501.
create or replace function public.costo_registrar(
  p_neumatico_id bigint,
  p_concepto     text,
  p_monto        numeric,
  p_fecha        date default null,
  p_notas        text default null,
  p_moneda       text default 'UYU'
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_n        public.neumaticos%rowtype;
  v_aut      record;
  v_concepto text := lower(btrim(coalesce(p_concepto, '')));
  v_moneda   text := upper(btrim(coalesce(p_moneda, 'UYU')));
  v_fecha    date := coalesce(p_fecha, current_date);
  v_notas    text := nullif(btrim(coalesce(p_notas, '')), '');
  v_monto    numeric;
  v_id       bigint;
begin
  select * into v_n from public.neumaticos n where n.id = p_neumatico_id;
  if not found then
    if auth.uid() is not null and public.is_admin() then
      raise exception 'neumático inexistente' using errcode = 'P0002';
    end if;
    raise exception 'permiso denegado' using errcode = '42501';
  end if;
  select * into v_aut from public.sucursal_autorizar_gestion(v_n.cliente_id);

  if v_concepto not in ('compra', 'reparacion', 'recauchutado', 'montaje', 'otro') then
    raise exception 'concepto inválido' using errcode = '23514';
  end if;
  if p_monto is null then
    raise exception 'monto obligatorio' using errcode = '22004';
  end if;
  if p_monto = 'NaN'::numeric or p_monto < 0 then
    raise exception 'monto inválido: debe ser mayor o igual a 0' using errcode = '23514';
  end if;
  v_monto := round(p_monto, 2);
  if v_monto > 9999999999.99 then
    raise exception 'monto fuera de rango' using errcode = '22003';
  end if;
  if v_moneda !~ '^[A-Z]{3}$' then
    raise exception 'moneda inválida: código de 3 letras' using errcode = '23514';
  end if;
  if v_fecha > current_date + 1 or v_fecha < date '2000-01-01' then
    raise exception 'fecha inválida' using errcode = '23514';
  end if;
  if v_notas is not null and length(v_notas) > 500 then
    raise exception 'notas demasiado largas (máximo 500 caracteres)' using errcode = '23514';
  end if;

  insert into public.costos_neumatico (cliente_id, neumatico_id, concepto, monto, moneda, fecha, notas, created_by)
  values (v_n.cliente_id, v_n.id, v_concepto, v_monto, v_moneda, v_fecha, v_notas, auth.uid())
  returning id into v_id;

  return jsonb_build_object('id', v_id, 'neumatico_id', v_n.id, 'concepto', v_concepto, 'monto', v_monto,
                            'moneda', v_moneda, 'fecha', v_fecha);
end
$$;
revoke all on function public.costo_registrar(bigint, text, numeric, date, text, text) from public, anon;
grant execute on function public.costo_registrar(bigint, text, numeric, date, text, text) to authenticated;

create or replace function public.costo_eliminar(p_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_c   public.costos_neumatico%rowtype;
  v_aut record;
begin
  select * into v_c from public.costos_neumatico c where c.id = p_id;
  if not found then
    if auth.uid() is not null and public.is_admin() then
      raise exception 'costo inexistente' using errcode = 'P0002';
    end if;
    raise exception 'permiso denegado' using errcode = '42501';
  end if;
  select * into v_aut from public.sucursal_autorizar_gestion(v_c.cliente_id);
  delete from public.costos_neumatico c where c.id = v_c.id;
  return jsonb_build_object('id', v_c.id, 'neumatico_id', v_c.neumatico_id);
end
$$;
revoke all on function public.costo_eliminar(bigint) from public, anon;
grant execute on function public.costo_eliminar(bigint) to authenticated;

-- -----------------------------------------------------------------------------
-- 5. v_costo_cubierta
-- -----------------------------------------------------------------------------
-- Una fila por cubierta visible (la RLS de neumaticos decide cuáles) y solo para quien puede ver costos
-- (costos_visibles): un perfil de sucursal no recibe filas, aunque ya lea neumaticos.precio_unidad y los eventos.
-- security_invoker: la RLS de neumaticos, costos_neumatico y eventos_neumatico es la de quien consulta.
--
-- Columnas de costo:
--   tiene_costo         hay al menos una entrada de costo.
--   moneda / monedas    moneda única (NULL si hay varias o ninguna) y la lista de monedas presentes.
--   moneda_mixta        hay más de una moneda: total, desglose y CPK son NULL.
--   costo_total         suma de todas las entradas (sin doble conteo); NULL si no hay costos o la moneda es mixta.
--   costo_por_concepto  jsonb {concepto: monto}; NULL en los mismos casos.
-- Columnas de km (de v_km_cubierta): km_totales y km_confiable.
--   cpk                 costo_total / km_totales SOLO con km_confiable y km_totales > 0; si no, NULL.
--   cpk_provisional     el mismo cociente cuando los km NO son confiables (faltan o decrecen odómetros) pero hay
--                       km_totales > 0: es una estimación y la interfaz la rotula como tal. NULL si no aplica.
-- Vida: la identidad del neumático es la carcasa y la vista acumula costos y km de TODAS sus vidas (recauchutados
-- incluidos), así que cpk es el CPK de la carcasa: costo neto total / suma de km de todas las vidas. Ver docs/08 apéndice I.
drop view if exists public.v_costo_cubierta;
create view public.v_costo_cubierta
with (security_invoker = true) as
select
  k.neumatico_id,
  k.cliente_id,
  k.vehiculo_id,
  coalesce(v.sucursal_id, n.sucursal_id)                                   as sucursal_id,
  k.idneumatico,
  k.numero_quema,
  n.marca,
  n.modelo,
  n.vida,
  n.condicion,
  k.estado,
  coalesce(n.fecha_compra, n.created_at::date)                             as fecha_alta,
  (c.n_items > 0)                                                          as tiene_costo,
  case when c.n_monedas = 1 then c.moneda end                              as moneda,
  c.monedas,
  (c.n_monedas > 1)                                                        as moneda_mixta,
  case when c.n_monedas = 1 then c.total end                               as costo_total,
  case when c.n_monedas = 1 then c.por_concepto end                        as costo_por_concepto,
  k.km_totales,
  k.km_confiable,
  case when c.n_monedas = 1 and k.km_confiable and k.km_totales > 0
       then c.total / k.km_totales end                                     as cpk,
  case when c.n_monedas = 1 and not k.km_confiable and k.km_totales > 0
       then c.total / k.km_totales end                                     as cpk_provisional
from public.v_km_cubierta k
join public.neumaticos n on n.id = k.neumatico_id
left join public.vehiculos v on v.id = n.vehiculo_id
left join lateral (
  select
    count(*)::int                  as n_items,
    count(distinct g.moneda)::int  as n_monedas,
    min(g.moneda)                  as moneda,
    array_agg(distinct g.moneda)   as monedas,
    sum(g.monto)                   as total,
    jsonb_object_agg(g.concepto, g.monto) as por_concepto
  from (
    select i.concepto, i.moneda, sum(i.monto) as monto
    from (
      -- Entradas manuales
      select m.concepto, m.moneda, m.monto
        from public.costos_neumatico m
       where m.neumatico_id = k.neumatico_id
      union all
      -- Eventos con costo que no son el montaje (el montaje repite el precio de compra)
      select case e.tipo when 'reparacion' then 'reparacion' when 'reencauche' then 'recauchutado' else 'otro' end,
             'UYU', e.costo
        from public.eventos_neumatico e
       where e.neumatico_id = k.neumatico_id and e.costo is not null and e.tipo <> 'montaje'
      union all
      -- Compra: precio_unidad, salvo que una entrada manual 'compra' la corrija
      select 'compra', 'UYU', n.precio_unidad
       where n.precio_unidad is not null
         and not exists (select 1 from public.costos_neumatico m
                          where m.neumatico_id = k.neumatico_id and m.concepto = 'compra')
      union all
      -- Compra sin precio_unidad: el costo del evento de montaje (una sola vez)
      select 'compra', 'UYU', max(e.costo)
        from public.eventos_neumatico e
       where n.precio_unidad is null and e.neumatico_id = k.neumatico_id
         and e.tipo = 'montaje' and e.costo is not null
         and not exists (select 1 from public.costos_neumatico m
                          where m.neumatico_id = k.neumatico_id and m.concepto = 'compra')
      having max(e.costo) is not null
    ) i
    group by i.concepto, i.moneda
  ) g
) c on true
where (select public.costos_visibles());

comment on view public.v_costo_cubierta is
  'Costo y CPK por cubierta (carcasa, todas las vidas): compra + eventos con costo + costos_neumatico sin doble conteo; moneda mixta -> NULL; cpk solo con km confiables (docs/08 apéndice I).';

revoke all on public.v_costo_cubierta from public, anon;
grant select on public.v_costo_cubierta to authenticated;

-- -----------------------------------------------------------------------------
-- 6. cpk_por_grupo(p_grupo, p_desde, p_hasta)
-- -----------------------------------------------------------------------------
-- CPK de un grupo = suma de costos / suma de km (ponderado), NUNCA el promedio de los CPK individuales. Solo entran
-- las cubiertas con costo en una única moneda, km confiables y km_totales > 0; las demás con costo se cuentan
-- aparte (n_sin_km) y las de moneda mixta no entran. Una fila por grupo y moneda (no se suman monedas distintas).
--   p_grupo        'marca' | 'modelo' (marca + modelo) | 'sucursal' (la del vehículo donde está montada o la de stock).
--   p_desde/hasta  cohorte: cubiertas dadas de alta (fecha de compra, o de creación si no hay) en el rango, ambos
--                  inclusivos y opcionales. Los costos y km de cada cubierta son siempre los de toda su vida: el
--                  rango elige qué cubiertas comparar (por época), no recorta sus costos.
--   p_cliente_id   opcional: acota a un cliente (para el admin, que de otro modo agrega todos los clientes).
--   muestra_baja   n_neumaticos < 5: el CPK de ese grupo es poco representativo.
-- SECURITY INVOKER sobre v_costo_cubierta: respeta la RLS (un perfil de sucursal no recibe filas).
drop function if exists public.cpk_por_grupo(text, date, date);
create or replace function public.cpk_por_grupo(
  p_grupo      text,
  p_desde      date default null,
  p_hasta      date default null,
  p_cliente_id bigint default null
)
returns table (
  grupo         text,
  clave         text,
  cliente_id    bigint,
  moneda        text,
  n_neumaticos  bigint,
  n_sin_km      bigint,
  km_totales    numeric,
  costo_total   numeric,
  cpk           numeric,
  muestra_baja  boolean
)
language plpgsql
stable
security invoker
set search_path = ''
as $$
begin
  if p_grupo is null or p_grupo not in ('marca', 'modelo', 'sucursal') then
    raise exception 'grupo inválido: marca, modelo o sucursal' using errcode = '22023';
  end if;
  if p_desde is not null and p_hasta is not null and p_desde > p_hasta then
    raise exception 'rango de fechas inválido' using errcode = '22023';
  end if;

  return query
  select
    p_grupo,
    case p_grupo
      when 'sucursal' then coalesce(min(s.nombre_suc), 'Sin sucursal')
      when 'marca'    then coalesce(nullif(btrim(min(s.etiqueta)), ''), 'Sin marca')
      else coalesce(nullif(btrim(min(s.etiqueta)), ''), 'Sin modelo') end,
    case when p_grupo = 'sucursal' then s.cli end,
    s.moneda,
    count(*) filter (where s.ok),
    count(*) filter (where not s.ok),
    coalesce(sum(s.km) filter (where s.ok), 0),
    sum(s.costo) filter (where s.ok),
    case when coalesce(sum(s.km) filter (where s.ok), 0) > 0
         then sum(s.costo) filter (where s.ok) / sum(s.km) filter (where s.ok) end,
    count(*) filter (where s.ok) < 5
  from (
    select
      case p_grupo
        when 'marca'    then lower(btrim(coalesce(x.marca, '')))
        when 'modelo'   then lower(btrim(coalesce(x.marca, ''))) || '|' || lower(btrim(coalesce(x.modelo, '')))
        else coalesce(x.sucursal_id::text, '-') end                                as gk,
      case p_grupo
        when 'marca'  then x.marca
        when 'modelo' then btrim(coalesce(x.marca, '') || ' ' || coalesce(x.modelo, ''))
      end                                                                           as etiqueta,
      case when p_grupo = 'sucursal' then su.nombre end            as nombre_suc,
      case when p_grupo = 'sucursal' then x.cliente_id end                         as cli,
      x.moneda,
      x.costo_total                                                                 as costo,
      x.km_totales                                                                  as km,
      (x.km_confiable and x.km_totales > 0)                                         as ok
    from public.v_costo_cubierta x
    left join public.sucursales su on p_grupo = 'sucursal' and su.id = x.sucursal_id
    where x.tiene_costo and x.costo_total is not null
      and (p_cliente_id is null or x.cliente_id = p_cliente_id)
      and (p_desde is null or x.fecha_alta >= p_desde)
      and (p_hasta is null or x.fecha_alta <= p_hasta)
  ) s
  group by s.gk, s.moneda, case when p_grupo = 'sucursal' then s.cli end
  order by 2, s.moneda;
end
$$;
revoke all on function public.cpk_por_grupo(text, date, date, bigint) from public, anon;
grant execute on function public.cpk_por_grupo(text, date, date, bigint) to authenticated;
