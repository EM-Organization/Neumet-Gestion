-- =============================================================================
-- NEUMET · Costos por cubierta y costo por km, CPK (hoja de ruta F4)
-- =============================================================================
-- Requiere 20261106000000 (init: neumaticos, audit_row), 20261106020000 (eventos_neumatico.costo),
-- 20261110010000 (sucursal_autorizar_gestion) y 20261115000000 (v_km_cubierta).
-- Sin begin/commit: la herramienta que aplica la migración ya la envuelve. Idempotente (reaplicable). No modifica
-- datos existentes. Diseño y reglas: docs/08-esquema-datos.md (apéndice I).
--
-- Qué agrega:
--   * costos_neumatico: entradas de costo por cubierta (compra, reparación, recauchutado, montaje, otro). Lectura por
--     RLS solo para admin y el perfil GLOBAL del cliente; el perfil de sucursal no ve costos. Sin escritura directa:
--     solo costo_registrar / costo_eliminar (SECURITY DEFINER, search_path = '', autorización dentro, auditadas).
--   * v_costo_cubierta: costo total y por concepto, km (de v_km_cubierta) y CPK por cubierta.
--   * cpk_por_grupo(): CPK ponderado por marca, modelo o sucursal.
--
-- Sin doble conteo. Hay tres fuentes de costo y dos de ellas ya existen:
--   a) neumaticos.precio_unidad: precio de compra de la cubierta.
--   b) eventos_neumatico.costo: neumatico_cambiar y neumatico_montar copian el precio de compra al evento de
--      'montaje' (solo en el alta o en el primer montaje de una cubierta «nuevo»). Es la MISMA compra, no un gasto
--      aparte. Una reparación o un reencauche con costo sí son gastos propios.
--   c) costos_neumatico: entradas manuales.
-- Regla de la vista: la compra es UNA sola, con esta precedencia: las entradas 'compra' de costos_neumatico (si las
-- hay, corrigen el dato original) > neumaticos.precio_unidad > el costo del evento de montaje (cubiertas cargadas sin
-- precio). Los eventos que no son 'montaje' suman con su concepto (reparacion, reencauche -> recauchutado, el resto
-- -> otro). Las demás entradas manuales suman siempre.
--
-- Moneda: precio_unidad y eventos_neumatico.costo no tienen moneda y se toman como 'UYU'. Si los costos de una
-- cubierta están en monedas distintas, el total, el desglose y el CPK son NULL y moneda_mixta es true: nunca se suman
-- monedas distintas.
--
-- Costo de las consultas: sin CTE recursiva ni funciones por fila propias; la vista usa un LATERAL correlacionado por
-- neumatico_id que solo toca índices (eventos_neumatico_neum_idx, costos_neumatico_neum_idx). El costo de km por
-- cubierta lo aporta v_km_cubierta (una llamada a km_tramos_cubierta por fila).
-- =============================================================================

