-- -----------------------------------------------------------------------------
-- 2. Tabla costos_neumatico
-- -----------------------------------------------------------------------------
create table if not exists public.costos_neumatico (
  id           bigint generated by default as identity primary key,
  cliente_id   bigint not null references public.clientes (id) on delete restrict,
  neumatico_id bigint not null,
  concepto     text not null check (concepto in ('compra', 'reparacion', 'recauchutado', 'montaje', 'otro')),
  monto        numeric(12,2) not null check (monto >= 0),
  moneda       text not null default 'UYU' check (moneda ~ '^[A-Z]{3}$'),
  fecha        date not null default current_date,
  notas        text check (notas is null or length(notas) <= 500),
  created_by   uuid default auth.uid(),
  created_at   timestamptz not null default now(),
  -- El costo es siempre de un neumático del mismo cliente. Si se borra la cubierta se borran sus costos (la
  -- eliminación queda en audit_log).
  constraint costos_neumatico_neumatico_fk foreign key (neumatico_id, cliente_id)
    references public.neumaticos (id, cliente_id) on delete cascade on update restrict
);

create index if not exists costos_neumatico_neum_idx    on public.costos_neumatico (neumatico_id);
create index if not exists costos_neumatico_cliente_idx on public.costos_neumatico (cliente_id, fecha desc);

drop trigger if exists trg_audit_costos_neumatico on public.costos_neumatico;
create trigger trg_audit_costos_neumatico after insert or update or delete on public.costos_neumatico
  for each row execute function public.audit_row();

-- RLS: lectura para admin y el perfil GLOBAL del cliente. El perfil de sucursal, api, anon y sin perfil no ven nada.
